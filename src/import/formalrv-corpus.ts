import { createHash } from 'node:crypto';
import { parseProject } from '../language/project';
import { formalrvMath } from './formalrv-math';
import { formalrvAssertionMath, parseFormalrvDefinition, parseFormalrvSpec, transcribeFormalrvDefinition, transcribeFormalrvSpec } from './formalrv-assertions';
import { FormalRVBlock, parseFormalRVSource, renderFormalRVProgram, splitFormalRVArguments } from './formalrv-program';

export interface FormalrvSnapshot {
  schemaVersion: number;
  repository: string;
  revision: string;
  roots: string[];
  sources: { path: string; sha256: string; text: string; members: { name: string; from: number; to: number }[] }[];
  imports: { from: string; import: string; to: string }[];
}

export interface FormalrvCorpus {
  files: Map<string, string>;
  coverage: Record<string, unknown>;
}

const digest = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');
const identifier = /^[A-Za-z][A-Za-z0-9_]*$/;

function outputName(path: string): string {
  const basename = path.split('/').at(-1)!.replace(/\.prog$/, '');
  return basename.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[._]/g, '-').toLowerCase() + '.qp';
}

/** A deterministic transcription of the pinned authored-program closure. */
export function generateFormalrvCorpus(snapshot: FormalrvSnapshot): FormalrvCorpus {
  if (snapshot.schemaVersion !== 1) throw new Error('Unsupported FormalRV snapshot version.');
  const sources = new Map(snapshot.sources.map(source => [source.path, source]));
  if (sources.size !== snapshot.sources.length) throw new Error('Duplicate FormalRV source path.');
  const outputPaths = new Map(snapshot.sources.map(source => [source.path, `examples/formalrv/${outputName(source.path)}`]));
  if (new Set(outputPaths.values()).size !== sources.size) throw new Error('FormalRV module filenames collide.');
  const blocks = new Map<string, FormalRVBlock[]>();
  for (const source of snapshot.sources) {
    if (digest(source.text) !== source.sha256) throw new Error(`Pinned source hash mismatch: ${source.path}`);
    blocks.set(source.path, parseFormalRVSource(source.text, source.path));
  }
  const owner = (path: string): string => {
    if (sources.has(path)) return path;
    const found = snapshot.sources.find(source => source.members.some(member => `${source.path}/${member.name}` === path));
    if (!found) throw new Error(`Import is outside the pinned closure: ${path}`);
    return found.path;
  };
  const files = new Map<string, string>();
  const coverageSources: Record<string, unknown>[] = [];
  const operationTotals: Record<string, number> = {};
  let specificationCount = 0, definitionCount = 0, algorithmCount = 0, conditionalPostconditions = 0, resourceCounters = 0;
  const dependencies = new Map<string, Set<string>>();

  for (const source of snapshot.sources) {
    const sourceBlocks = blocks.get(source.path)!;
    const stem = source.path.split('/').at(-1)!.replace(/\.prog$/, '');
    const sourceUrl = `${snapshot.repository}/tree/${snapshot.revision}/${source.path}`;
    const lines = [
      `qparam FormalRV_${stem.replace(/[^A-Za-z0-9_]/g, '_')}`,
      `title ${JSON.stringify(`FormalRV · ${stem}`)}`,
      `description ${JSON.stringify('Complete authored-source syntax transcription. Claims remain unverified in QP; see docs/literature/gidney.md and coverage.json.')}`,
      '',
      '// Generated by scripts/import-formalrv.cjs from the pinned source fixture.',
      `// Source: ${sourceUrl}`,
      `// SHA-256: ${source.sha256}`,
      '// Mathematical assertions and resource expressions are preserved, not proved.',
      '',
    ];
    const imports = new Set<string>();
    dependencies.set(source.path, imports);
    const signatures = new Set<string>();
    const importedMembers: { source: string; target: string; qpModule: string; projected: boolean }[] = [];
    const declarationCoverage: Record<string, unknown>[] = [];
    const operationCounts: Record<string, number> = {};
    const algorithms: string[] = [], specifications: string[] = [];
    const incompleteContracts: Record<string, unknown>[] = [];

    for (const block of sourceBlocks) {
      let output = '';
      let disposition = 'transcribed';
      switch (block.kind) {
        case 'use': {
          const requested = block.source.slice(3).trim();
          const edge = snapshot.imports.find(item => item.from === source.path && item.import === requested);
          if (!edge) throw new Error(`Unpinned import ${requested} in ${source.path}.`);
          const target = owner(edge.to);
          const qpModule = outputPaths.get(target)!;
          importedMembers.push({ source: requested, target: edge.to, qpModule, projected: edge.to !== target });
          if (!imports.has(target)) {
            imports.add(target);
            output = `import ${JSON.stringify(`./${qpModule.split('/').at(-1)}`)}`;
          } else disposition = 'deduplicated-import';
          break;
        }
        case 'params': case 'arrays': case 'amps': {
          const names = splitFormalRVArguments(block.source.slice(block.kind.length).trim());
          if (names.some(name => !/^(?:[A-Za-z][A-Za-z0-9_]*|[αβω])$/.test(name))) throw new Error(`Unsupported global declaration in ${source.path}:${block.line}.`);
          const type = block.kind === 'params' ? 'Nat' : block.kind === 'arrays' ? 'Nat[]' : 'Math';
          output = names.map(name => `parameter ${name} : ${type}`).join('\n');
          break;
        }
        case 'map': {
          const match = /^map\s+([A-Za-z][A-Za-z0-9_]*)\s*\(([^()]*)\)\s*\(([^()]*)\)\s*=\s*([\s\S]+)$/.exec(block.source);
          if (!match) throw new Error(`Unsupported map header in ${source.path}:${block.line}.`);
          const parameters = splitFormalRVArguments(match[2]);
          if (parameters.some(parameter => !identifier.test(parameter)) || !identifier.test(match[3].trim())) throw new Error('Map arguments must be identifiers.');
          output = `map ${match[1]}(${parameters.map(parameter => `${parameter} : Nat`).join(', ')})(${match[3].trim()} : Nat) := $${formalrvMath(match[4])}$`;
          break;
        }
        case 'define': {
          definitionCount++;
          const definition = parseFormalrvDefinition(block.source);
          if (!signatures.has(definition.name)) {
            signatures.add(definition.name);
            const equations = sourceBlocks.filter(candidate => candidate.kind === 'define' && candidate.name === definition.name)
              .map(candidate => parseFormalrvDefinition(candidate.source));
            if (equations.some(equation => equation.patterns.length !== definition.patterns.length)) throw new Error(`Definition arity changes: ${definition.name}.`);
            const used = new Set<string>();
            const parameters = definition.patterns.map((_, index) => {
              const patterns = equations.map(equation => equation.patterns[index]);
              let candidate = patterns.find(pattern => identifier.test(pattern));
              candidate ??= patterns.map(pattern => /^([A-Za-z][A-Za-z0-9_]*)\s*\+\s*1$/.exec(pattern)?.[1]).find(Boolean);
              if (!candidate || used.has(candidate)) candidate = `argument${index}`;
              used.add(candidate);
              return `${candidate} : Math`;
            });
            output = `define ${definition.name}(${parameters.join(', ')})\n`;
          }
          output += transcribeFormalrvDefinition(block.source);
          break;
        }
        case 'gadget': case 'program': {
          algorithmCount++;
          const rendered = renderFormalRVProgram(block, formalrvAssertionMath);
          output = rendered.text;
          algorithms.push(block.name!);
          for (const operation of rendered.operations) {
            operationCounts[operation.kind] = (operationCounts[operation.kind] ?? 0) + 1;
            operationTotals[operation.kind] = (operationTotals[operation.kind] ?? 0) + 1;
          }
          break;
        }
        case 'spec': {
          specificationCount++;
          specifications.push(block.name!);
          const contract = parseFormalrvSpec(block.source);
          conditionalPostconditions += contract.clauses.filter(clause => 'condition' in clause && clause.condition).length;
          resourceCounters += contract.clauses.reduce((count, clause) => count + (clause.kind === 'resource' ? clause.entries.length : 0), 0);
          const missing = ['assumes', 'ensures'].filter(kind => !contract.clauses.some(clause => clause.kind === kind));
          if (missing.length) incompleteContracts.push({ name: block.name, missing });
          output = transcribeFormalrvSpec(block.source);
          break;
        }
        case 'code': {
          const match = /^code\s+([A-Za-z][A-Za-z0-9_]*)\s+([\s\S]+)$/.exec(block.source);
          if (!match) throw new Error(`Unsupported code declaration in ${source.path}:${block.line}.`);
          output = `configuration ${match[1]} $${formalrvMath(match[2])}$`;
          break;
        }
      }
      const generatedStartLine = lines.length + 1;
      if (output) lines.push(output, '');
      // Embedded newlines count as physical source lines in the generated file.
      const start = lines.slice(0, generatedStartLine - 1).join('\n').split('\n').length + (generatedStartLine > 1 ? 1 : 0);
      declarationCoverage.push({
        kind: block.kind, ...(block.name ? { name: block.name } : {}),
        sourceLines: [block.line, block.endLine], sourceSha256: digest(block.source), disposition,
        generatedLines: output ? [start, start + output.split('\n').length - 1] : null,
      });
    }
    const text = lines.join('\n');
    const outputPath = outputPaths.get(source.path)!;
    files.set(outputPath, text);
    coverageSources.push({
      path: source.path, sourceUrl, sha256: source.sha256, output: outputPath, outputSha256: digest(text),
      sourceMembers: source.members.map(member => ({ ...member, sha256: digest(source.text.slice(member.from, member.to)),
        sourceUrl: `${snapshot.repository}/blob/${snapshot.revision}/${source.path}/${member.name}` })),
      imports: importedMembers, operations: operationCounts, algorithms, specifications,
      contractsMissingStateClauses: incompleteContracts, declarations: declarationCoverage,
    });
  }

  const roots = snapshot.roots.map(root => {
    if (!sources.has(root)) throw new Error(`Root is outside the pinned closure: ${root}`);
    const closure = new Set<string>();
    const visit = (path: string) => { if (closure.has(path)) return; closure.add(path); dependencies.get(path)?.forEach(visit); };
    visit(root);
    const declarations = [...closure].flatMap(path => blocks.get(path)!);
    const specs = new Set(declarations.filter(block => block.kind === 'spec').map(block => block.name));
    const programs = declarations.filter(block => block.program);
    const originalNodes = new Map<string, FormalRVBlock[]>();
    const visitOriginal = (path: string) => {
      if (originalNodes.has(path)) return;
      const stage = sources.get(owner(path))!;
      const member = path === stage.path ? undefined : stage.members.find(item => `${stage.path}/${item.name}` === path)!;
      const originalBlocks = member ? parseFormalRVSource(stage.text.slice(member.from, member.to), path) : blocks.get(path)!;
      originalNodes.set(path, originalBlocks);
      for (const block of originalBlocks.filter(item => item.kind === 'use')) {
        const requested = block.source.slice(3).trim();
        const edge = snapshot.imports.find(item => item.from === path && item.import === requested);
        if (!edge) throw new Error(`Unpinned original import ${requested} in ${path}.`);
        visitOriginal(edge.to);
      }
    };
    visitOriginal(root);
    const originalPrograms = [...originalNodes.values()].flat().filter(block => block.program);
    const originalProgramNames = new Set(originalPrograms.map(block => block.name));
    return { source: root, output: outputPaths.get(root), modules: [...closure].map(path => outputPaths.get(path)),
      algorithms: programs.length, specifications: declarations.filter(block => block.kind === 'spec').length,
      originalImportedAlgorithms: originalPrograms.length,
      additionalAvailableAlgorithms: programs.filter(block => !originalProgramNames.has(block.name)).map(block => block.name),
      algorithmsWithoutSourceContract: programs.filter(block => !specs.has(block.name)).map(block => ({ name: block.name, source: block.path, line: block.line })) };
  });
  const coverage = {
    schemaVersion: 1, status: 'syntax-transcribed-not-verified', repository: snapshot.repository, revision: snapshot.revision,
    sourceFixture: 'test/fixtures/formalrv/gidney.json',
    snapshotHashPolicy: 'SHA-256 hashes identify the pinned UTF-8 joined source snapshot and its members, including captured line endings. Checkout line endings can differ from Git blobs; revision identifies source content ancestry.',
    scope: 'Authored .prog programs, mathematical definitions, contracts and code configuration declarations; generated .qppm/.qec/.sysprog artifacts and machine verdicts are not imported.',
    importProjection: 'Imports of individual source-stage members use the owning QP module once. Its additional declarations are available but its algorithms are never automatically executed.',
    totals: { modules: sources.size, algorithms: algorithmCount, specifications: specificationCount, definitionEquations: definitionCount,
      operations: Object.values(operationTotals).reduce((total, count) => total + count, 0), operationKinds: operationTotals,
      conditionalPostconditions, resourceCounters },
    roots, sources: coverageSources,
  };
  files.set('examples/formalrv/coverage.json', JSON.stringify(coverage, null, 2) + '\n');
  return { files, coverage };
}

/** Resolve every generated module using the same syntax resolver as the editor. */
export function validateFormalrvCorpus(corpus: FormalrvCorpus): void {
  for (const [path] of corpus.files) {
    if (!path.endsWith('.qp')) continue;
    const project = parseProject(path, dependency => {
      const source = corpus.files.get(dependency);
      if (source === undefined) throw new Error(`Missing generated dependency: ${dependency}`);
      return source;
    });
    const errors = project.document.diagnostics.filter(diagnostic => diagnostic.severity === 'error');
    if (errors.length) throw new Error(`${path}:\n${errors.map(error => `${error.line + 1}:${error.column + 1}: ${error.message}`).join('\n')}`);
  }
}
